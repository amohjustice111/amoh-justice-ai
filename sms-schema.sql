-- AMOH JUSTICE AI SMS delivery audit log.
-- Run this migration in Supabase SQL Editor. The table is private: no client policies are created.
create table if not exists public.amoh_sms_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  recipient_phone text not null,
  message text not null check (char_length(message) <= 1000),
  message_type text not null check (message_type in ('welcome','verification','account_update','announcement')),
  event_key text unique,
  status text not null default 'sent' check (status in ('queued','sent','failed')),
  provider_message_id text,
  provider_cost text,
  sent_by text,
  created_at timestamptz not null default now()
);
alter table public.amoh_sms_logs enable row level security;
revoke all on public.amoh_sms_logs from anon, authenticated;
create index if not exists amoh_sms_logs_created_at_idx on public.amoh_sms_logs(created_at desc);
create index if not exists amoh_sms_logs_user_created_idx on public.amoh_sms_logs(user_id, created_at desc);
